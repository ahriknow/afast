/// Writes a single service's generated Kotlin code to a `.kt` file.
#[cfg(feature = "kt")]
fn write_service_kt(
    svc: &Service,
    dir: &Path,
    calls: &[crate::KtCallType],
    debug: bool,
) -> Result<(), Error> {
    use std::fs;

    let code = generate_service_kt(svc, calls, debug);
    let file_name = format!("{}.kt", svc.name);
    let file_path = dir.join(&file_name);
    fs::write(&file_path, &code).map_err(|e| Error::Io {
        message: e.to_string(),
    })?;

    Ok(())
}

impl AFast {
    /// Returns the complete generated Kotlin code as a single string,
    /// including common.kt content concatenated with every service file.
    /// Primarily used for testing and inspection.
    #[cfg(feature = "kt")]
    pub fn get_kt_code(&self) -> String {
        let seq64 = cfg!(feature = "seq64");
        let has_ws = true;
        let has_tcp = true;
        let common = generate_common_kt(&self.services, seq64, has_ws, has_tcp);
        let mut parts = vec![common];
        for svc in &self.services {
            parts.push(generate_service_kt(
                svc,
                &[
                    crate::KtCallType::Http,
                    crate::KtCallType::Ws,
                    crate::KtCallType::Tcp,
                ],
                false,
            ));
        }
        parts.join("\n\n")
    }

    /// Generates Kotlin client code for all registered services and writes
    /// the files to `dir`.  Produces one `common.kt` with shared types and
    /// one `{service}.kt` per service.  The `calls` slice controls which
    /// transport methods (Http, Ws, Tcp) are included.
    #[cfg(feature = "kt")]
    pub fn generate_kt(
        &self,
        dir: &Path,
        calls: &[crate::KtCallType],
        debug: bool,
    ) -> Result<(), Error> {
        use std::fs;

        fs::create_dir_all(dir).map_err(|e| Error::Io {
            message: e.to_string(),
        })?;

        let seq64 = cfg!(feature = "seq64");
        let has_ws = calls.iter().any(|c| matches!(c, crate::KtCallType::Ws));
        let has_tcp = calls.iter().any(|c| matches!(c, crate::KtCallType::Tcp));
        let common = generate_common_kt(&self.services, seq64, has_ws, has_tcp);
        fs::write(dir.join("common.kt"), &common).map_err(|e| Error::Io {
            message: e.to_string(),
        })?;

        for svc in &self.services {
            write_service_kt(svc, dir, calls, debug)?;
        }

        Ok(())
    }
}
