// ─── SseRouteInfo ────────────────────────────────────────────────

/// Stores information about a registered SSE route.
#[derive(Clone)]
pub struct SseRouteInfo {
    /// The path pattern (e.g. `"/notifications/:user_id"`).
    pub path: &'static str,
    /// The handler name for logging/diagnostics.
    pub handler_name: &'static str,
    /// The compiled route pattern.
    pub(crate) pattern: crate::app::ordinary::RoutePattern,
    /// The SSE handler invoker.
    pub invoker: &'static dyn SseHandlerInvoker,
    /// The service this route belongs to.
    pub service_name: String,
}
